import random

from django.shortcuts import render
from django.utils import timezone

WEEKDAYS = [
    'Понеділок',
    'Вівторок',
    'Середа',
    'Четвер',
    "П'ятниця",
    'Субота',
    'Неділя',
]

QUOTES = [
    'Єдиний спосіб робити чудову роботу — любити те, що ти робиш. — Стів Джобс',
    'Спочатку вони тебе ігнорують, потім сміються з тебе, потім борються з тобою, а потім ти перемагаєш. — Махатма Ґанді',
    'Не важливо, як повільно ти йдеш, доки ти не зупиняєшся. — Конфуцій',
    'Краще зробити і шкодувати, ніж шкодувати, що не зробив. — Джованні Боккаччо',
    'Хто хоче — шукає можливості, хто не хоче — шукає причини. — Сократ',
    'Знання — сила. — Френсіс Бекон',
    'Життя — це те, що трапляється з тобою, поки ти будуєш інші плани. — Джон Леннон',
]


def index(request):
    today = timezone.localtime()
    context = {
        'weekday': WEEKDAYS[today.weekday()],
        'quote': random.choice(QUOTES),
    }
    return render(request, 'home/index.html', context)
